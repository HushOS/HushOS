/*
 * Renders every email once, at build time, into src/rendered/*.ts. The running
 * server then needs neither React nor React Email: it substitutes the
 * placeholders below and sends. Re-run with `bun run email:render` after editing
 * a template; CI fails if the committed output is stale.
 */
/*
 * The plain-text part leaves out the hidden marker at the end of every message:
 * it is only there so Gmail never folds the HTML's end away, and in text it would show.
 * Headings keep their case: upper-casing them would turn a placeholder such as
 * {{granterName}} into {{GRANTERNAME}}, which the server never fills, and a
 * person's name is theirs to spell. Every placeholder in the text must be one the
 * HTML has, and every one the HTML shows must reach the text.
 */
const headings = ['h1', 'h2', 'h3', 'h4', 'h5', 'h6'].map((selector) => ({
    selector,
    options: { uppercase: false },
}));
const plain = (html: string) => {
    const text = toPlainText(html.replace(/<span data-marker=""[^>]*>[^<]*<\/span>/, ''), {
        selectors: headings,
    });
    if (text.includes('{{marker}}')) throw new Error('The marker leaked into the plain text.');
    for (const [part, body] of [
        ['HTML', html],
        ['plain text', text],
    ] as const)
        if (body.split('{{').length - 1 !== [...body.matchAll(/\{\{\w+\}\}/g)].length)
            throw new Error(`The ${part} has a placeholder broken apart.`);
    for (const [token] of text.matchAll(/\{\{\w+\}\}/g))
        if (!html.includes(token))
            throw new Error(`The plain text has ${token}, which no one fills.`);
    for (const [token] of html.matchAll(/\{\{\w+\}\}/g))
        if (token !== '{{marker}}' && token !== '{{logoUrl}}' && !text.includes(token))
            throw new Error(`The plain text lost ${token}.`);
    return text;
};

export const PLACEHOLDERS = {
    verificationUrl: '{{verificationUrl}}',
    logoUrl: '{{logoUrl}}',
    marker: '{{marker}}',
} as const;

const purposes = ['register', 'recover'] as const;
const rendered: Record<string, { html: string; text: string }> = {};
for (const purpose of purposes) {
    const html = await render(
        <VerifyEmail
            purpose={purpose}
            verificationUrl={PLACEHOLDERS.verificationUrl}
            logoUrl={PLACEHOLDERS.logoUrl}
            marker={PLACEHOLDERS.marker}
        />,
    );
    for (const token of Object.values(PLACEHOLDERS))
        if (!html.includes(token)) throw new Error(`Rendered ${purpose} email lacks ${token}.`);
    rendered[purpose] = { html, text: plain(html) };
}

const source = `/* Generated by \`bun run email:render\` from src/templates/verify-email.tsx. Do not edit. */
export const verifyEmail = ${JSON.stringify(rendered, null, 4)} as const;
`;
await Bun.write(new URL('../src/rendered/verify-email.ts', import.meta.url), source);
console.info(`Rendered ${purposes.length} verification emails.`);

