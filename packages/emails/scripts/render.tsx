/*
 * A dissolved family's notices: to its last member (with the day its folders are deleted,
 * filled by the server) and to whoever was still joining it. The family's name is the
 * organiser's, escaped like every value.
 */
export const DISSOLVED_PLACEHOLDERS = {
    groupName: '{{groupName}}',
    deletesOn: '{{deletesOn}}',
    logoUrl: '{{logoUrl}}',
    marker: '{{marker}}',
} as const;
const dissolvedKinds: FamilyDissolvedKind[] = ['dissolved', 'accepted', 'invited'];
const dissolvedRendered: Record<string, { html: string; text: string }> = {};
for (const kind of dissolvedKinds) {
    const html = await render(
        <FamilyDissolved
            kind={kind}
            groupName={DISSOLVED_PLACEHOLDERS.groupName}
            deletesOn={DISSOLVED_PLACEHOLDERS.deletesOn}
            logoUrl={DISSOLVED_PLACEHOLDERS.logoUrl}
            marker={DISSOLVED_PLACEHOLDERS.marker}
        />,
    );
    const needed = [
        DISSOLVED_PLACEHOLDERS.groupName,
        DISSOLVED_PLACEHOLDERS.logoUrl,
        DISSOLVED_PLACEHOLDERS.marker,
        ...(kind === 'dissolved' ? [DISSOLVED_PLACEHOLDERS.deletesOn] : []),
    ];
    for (const token of needed)
        if (!html.includes(token))
            throw new Error(`Rendered ${kind} family notice lacks ${token}.`);
    if (kind !== 'dissolved' && html.includes(DISSOLVED_PLACEHOLDERS.deletesOn))
        throw new Error(`The ${kind} family notice names a deletion date it is never given.`);
    dissolvedRendered[kind] = { html, text: plain(html) };
}
await Bun.write(
    new URL('../src/rendered/family-dissolved.ts', import.meta.url),
    `/* Generated by \`bun run email:render\` from src/templates/family-dissolved.tsx. Do not edit. */
export const familyDissolved = ${JSON.stringify(dissolvedRendered, null, 4)} as const;
`,
);
console.info(`Rendered ${dissolvedKinds.length} dissolved family notices.`);

/*
 * Sign-up for an address that has an account, or recovery for one that has none: where to go
 * instead, and when it was asked (written by the server, in UTC). Fixed words and the app's
 * own links; no token, and nothing anyone typed.
 */
export const ACCOUNT_NOTICE_PLACEHOLDERS = {
    signInUrl: '{{signInUrl}}',
    recoverUrl: '{{recoverUrl}}',
    registerUrl: '{{registerUrl}}',
    when: '{{when}}',
    logoUrl: '{{logoUrl}}',
    marker: '{{marker}}',
} as const;
const accountNoticeKinds: AccountNoticeKind[] = ['exists', 'none'];
const accountNoticeRendered: Record<string, { html: string; text: string }> = {};
for (const kind of accountNoticeKinds) {
    const html = await render(<AccountNotice kind={kind} {...ACCOUNT_NOTICE_PLACEHOLDERS} />);
    const P = ACCOUNT_NOTICE_PLACEHOLDERS;
    const needed =
        kind === 'exists'
            ? [P.signInUrl, P.recoverUrl, P.when, P.logoUrl, P.marker]
            : [P.registerUrl, P.when, P.logoUrl, P.marker];
    for (const token of needed)
        if (!html.includes(token))
            throw new Error(`Rendered ${kind} account notice lacks ${token}.`);
    for (const token of Object.values(P))
        if (!needed.includes(token) && html.includes(token))
            throw new Error(`The ${kind} account notice has ${token}, which it is never given.`);
    accountNoticeRendered[kind] = { html, text: plain(html) };
}
await Bun.write(
    new URL('../src/rendered/account-notice.ts', import.meta.url),
    `/* Generated by \`bun run email:render\` from src/templates/account-notice.tsx. Do not edit. */
export const accountNotice = ${JSON.stringify(accountNoticeRendered, null, 4)} as const;
`,
);
console.info(`Rendered ${accountNoticeKinds.length} account notices.`);
